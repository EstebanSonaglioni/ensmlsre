#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOF
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE ROLE ${APP_DB_USER} LOGIN PASSWORD '${APP_DB_PASSWORD}';
CREATE ROLE ${MIGRATION_DB_USER} LOGIN PASSWORD '${MIGRATION_DB_PASSWORD}';

GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${APP_DB_USER};
GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${MIGRATION_DB_USER};

GRANT USAGE ON SCHEMA public TO ${APP_DB_USER};
GRANT USAGE, CREATE ON SCHEMA public TO ${MIGRATION_DB_USER};

ALTER DEFAULT PRIVILEGES FOR ROLE ${MIGRATION_DB_USER} IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_DB_USER};

ALTER DEFAULT PRIVILEGES FOR ROLE ${MIGRATION_DB_USER} IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO ${APP_DB_USER};
EOF
